# Считываем количество сотрудников
n = int(input())

# Первое множество: фамилии, которые уже встречались хотя бы раз
seen = set()
# Второе множество: фамилии, которые встречаются более одного раза (однофамильцы)
duplicates = set()

# Проходим по всем фамилиям
for _ in range(n):
    surname = input().strip()  # Читаем фамилию и убираем лишние пробелы
    if surname in seen:
        # Если фамилия уже была в seen, добавляем её в duplicates
        duplicates.add(surname)
    else:
        # Иначе добавляем в множество встреченных фамилий
        seen.add(surname)

# Результат — количество элементов в duplicates
print(len(duplicates))
